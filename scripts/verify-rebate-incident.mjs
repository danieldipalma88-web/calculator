import assert from "node:assert/strict";
import { incidentState, syncIncident } from "./report-rebate-incident.mjs";

const healthy = { ok: true, degraded: false, service: { available: true }, primary: { verified: true }, certificate: { ok: true }, backup: { verified: true }, registry: { verified: true } };
const degraded = { ...healthy, degraded: true, primary: { verified: false }, service: { available: false }, certificate: { ok: false } };
const outage = { ...degraded, ok: false, backup: { verified: false } };
let issues = [];
let requests = [];
const options = { token: "fixture-only", runUrl: "https://github.com/danieldipalma88-web/calculator/actions/runs/123", fetchImpl: async (url, init) => {
  assert.ok(url.startsWith("https://api.github.com/repos/danieldipalma88-web/calculator/issues"));
  assert.equal(init.redirect, "error");
  assert.ok(init.signal);
  requests.push({ method: init.method, body: init.body && JSON.parse(init.body) });
  return Response.json(init.method === "GET" ? issues : { number: 42 });
} };
const run = report => syncIncident({ ...options, report });
assert.equal(incidentState(null), "monitor-incomplete");
assert.equal(incidentState({ ...degraded, ok: true, degraded: false }), "monitor-incomplete", "Summary flags cannot falsely close an incident");
assert.equal(incidentState({ ...healthy, registry: { verified: false } }), "monitor-incomplete");
assert.equal(await run(healthy), "healthy-no-incident");
assert.equal(requests.filter(r => r.method !== "GET").length, 0);
requests = [];
assert.equal(await run(degraded), "opened");
const created = requests.find(r => r.method === "POST").body;
assert.deepEqual(created.assignees, ["danieldipalma88-web"]);
assert.ok(!created.body.includes("fixture-only"));
issues = [{ ...created, number: 42, user: { login: "github-actions[bot]" } }];
requests = [];
assert.equal(await run(degraded), "unchanged");
assert.equal(requests.length, 1, "No repeated comments or edits for an unchanged incident");
requests = [];
assert.equal(await run(outage), "updated");
assert.equal(requests.filter(r => r.method === "POST").length, 1);
assert.equal(requests.filter(r => r.method === "PATCH").length, 1);
requests = [];
assert.equal(await run(healthy), "recovered");
assert.equal(requests.at(-1).body.state, "closed");
issues = [{ ...issues[0], user: { login: "another-user" } }];
requests = [];
assert.equal(await run(healthy), "healthy-no-incident", "Never alter user-created issues");
issues = [];
assert.equal(await run(null), "opened", "Missing monitor output must not be interpreted as recovery");
await assert.rejects(syncIncident({ ...options, report: healthy, runUrl: "https://example.com" }), /Invalid incident/);
await assert.rejects(syncIncident({ ...options, report: healthy, fetchImpl: async () => new Response("denied", { status: 403 }) }), /HTTP 403/);
console.log("Incident alerts: deduplicated degraded/outage/recovery, unknown health, public fixed-data only, repository and issue ownership guards passed.");
